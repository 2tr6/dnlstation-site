    check('Yanlış mevcut şifre reddedilir', r.status_code == 422 and 'current_password' in r.json()['error']['fields'], r.text)
    r = cf.post('/account/password', {'current_password': 'Yeni.Sifre-2026x', 'password': 'Diger.Sifre-2026', 'password_confirm': 'Diger.Sifre-2026'})
