    check('Doğru giriş (büyük/küçük harf duyarsız e-posta)', r.status_code == 200, r.text)
    check('Girişte oturum kimliği yenilenir', c.s.cookies.get('DNLSESS') != old_session)
    check('Beni hatırla çerezi verildi', c.s.cookies.get('DNLREM') is not None)
    r = c.post('/me', {})
    check('Girişten sonra eski CSRF anahtarı geçersiz', r.status_code in (405, 419))

    print('== M1 Beni hatırla ==')
    rem = c.s.cookies.get('DNLREM')
    c3 = Client(); c3.s.cookies.set('DNLREM', rem, domain='127.0.0.1', path='/')
    r = c3.me()
    check('Hatırlama çerezi ile oturum açılır', r.status_code == 200, r.text)
    check('Hatırlama anahtarı kullanımda döndürülür', c3.s.cookies.get('DNLREM') not in (None, rem))
    c4 = Client(); c4.s.cookies.set('DNLREM', rem, domain='127.0.0.1', path='/')
    check('Kullanılmış hatırlama anahtarı tekrar çalışmaz', c4.me().status_code == 401)
    c5 = Client(); c5.s.cookies.set('DNLREM', 'a' * 24 + ':' + 'b' * 43, domain='127.0.0.1', path='/')
    check('Sahte hatırlama anahtarı reddedilir', c5.me().status_code == 401)

    print('== M1 Kaba kuvvet koruması ==')
    cb = Client(); cb.refresh_csrf()
    for i in range(5):
        cb.post('/auth/login', {'email': 'sahip@arena.test', 'password': f'yanlis-{i}-sifre'})
    r = cb.post('/auth/login', {'email': 'sahip@arena.test', 'password': 'Guclu.Sifre-2026'})
    check('5 hatalı denemeden sonra hesap geçici kilitlenir', r.status_code == 429 and r.json()['error']['code'] == 'locked', r.text)

    print('== M1 Şifremi unuttum / sıfırlama ==')
    cf = Client(); cf.refresh_csrf()
    r1 = cf.post('/auth/forgot', {'email': 'sahip@arena.test'})
